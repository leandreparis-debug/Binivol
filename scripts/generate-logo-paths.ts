/**
 * Generates `src/components/brand/logoPaths.ts`: the glyphs of « binivol »
 * and of « b » in Inter Tight 700, converted to SVG paths (y down, units of
 * 1/100 em, baseline at y = 0), so that the logo never depends on a font
 * being loaded (favicon, PNG for e-mails, PDF). Run once when the logo
 * changes: `pnpm logo:paths <InterTight-Bold.ttf>` (the font is not stored).
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import fontkit from "@pdf-lib/fontkit";

interface FontkitPath {
  scale(x: number, y: number): FontkitPath;
  translate(x: number, y: number): FontkitPath;
  toSVG(): string;
}

const TRACKING = -0.05; // em, between letters of the wordmark

function main(): void {
  const file = process.argv[2];
  if (!file) throw new Error("Usage : pnpm logo:paths <InterTight-Bold.ttf>");
  const font = fontkit.create(readFileSync(file));
  const scale = 100 / font.unitsPerEm;

  const word = (text: string, tracking: number) => {
    const run = font.layout(text);
    let x = 0;
    const parts: string[] = [];
    run.glyphs.forEach((glyph, i) => {
      // fontkit paths have scale() and translate() at run time (missing from its types).
      const p = (glyph.path as unknown as FontkitPath).scale(scale, -scale).translate(x, 0);
      parts.push(p.toSVG());
      x +=
        (run.positions[i]?.xAdvance ?? 0) * scale +
        (i < run.glyphs.length - 1 ? tracking * 100 : 0);
    });
    const bbox = run.glyphs.reduce(
      (acc, g, i) => {
        const offset = run.positions
          .slice(0, i)
          .reduce((s, p) => s + p.xAdvance * scale + tracking * 100, 0);
        return {
          minX: Math.min(acc.minX, g.bbox.minX * scale + offset),
          maxX: Math.max(acc.maxX, g.bbox.maxX * scale + offset),
          top: Math.max(acc.top, g.bbox.maxY * scale),
          bottom: Math.min(acc.bottom, g.bbox.minY * scale),
        };
      },
      { minX: Infinity, maxX: -Infinity, top: -Infinity, bottom: Infinity },
    );
    const r = (n: number) => Math.round(n * 100) / 100;
    return {
      d: parts.join(" ").replace(/(\d+\.\d{2})\d+/g, "$1"),
      advance: r(x),
      minX: r(bbox.minX),
      maxX: r(bbox.maxX),
      top: r(bbox.top),
      bottom: r(bbox.bottom),
    };
  };

  const wordmark = word("binivol", TRACKING);
  const letter = word("b", 0);
  const out = `// Generated by scripts/generate-logo-paths.ts from Inter Tight 700. Do not edit.
// Units: 1/100 em, y down, baseline at y = 0 (glyphs go up into negative y).

/** « binivol », tracking ${String(TRACKING)} em. */
export const WORDMARK = ${JSON.stringify({ ...wordmark, top: -wordmark.top, bottom: -wordmark.bottom }, null, 2)} as const;

/** « b » alone (icon). */
export const LETTER_B = ${JSON.stringify({ ...letter, top: -letter.top, bottom: -letter.bottom }, null, 2)} as const;
`;
  const target = path.resolve(import.meta.dirname, "../src/components/brand/logoPaths.ts");
  writeFileSync(target, out, "utf8");
  process.stdout.write(`Tracés du logo écrits : ${target}\n`);
}

main();
